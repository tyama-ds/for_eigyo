def make_docs() -> list[dict]:
    docs = []
    n = 0

    def add(title, ab, cl, fi, ft, ipc, rel, year, cite=None):
        nonlocal n
        n += 1
        doc_id = f"JP{year}-{100000 + n:06d}A"
        docs.append({"doc_id": doc_id, "title": title, "abstract": ab, "claims": cl, "FI": fi, "FT": ft, "IPC": ipc,
                     "pub_date": f"{year}-{rng.randint(1, 12):02d}-{rng.randint(1, 28):02d}",
                     "applicant": rng.choice(APPLICANTS[:4] if rel >= 1 else APPLICANTS), "citations": cite or [], "_rel": rel})

    # 適合 24 件（8 テンプレ × 3 バリエーション）
    for i in range(24):
        t, ab, cl = RELEVANT[i % len(RELEVANT)]
        fi, ft, ipc = REL_CODES[i % len(REL_CODES)]
        suffix = ["", "（第2実施形態）", "および装置"][i // len(RELEVANT)]
        add(t + suffix, ab, cl, list(fi), list(ft), list(ipc), 3, 2012 + (i % 12))
    # 部分適合 20 件
    for i in range(20):
        t, ab, cl, fi, ft, ipc = PARTIAL[i % len(PARTIAL)]
        add(t, ab, cl, list(fi), list(ft), list(ipc), 1 + (i % 2), 2010 + (i % 14))
    # 鉄鋼だが非適合 40 件
    for i in range(40):
        t, ab, cl, fi, ft, ipc = STEEL_NONREL[i % len(STEEL_NONREL)]
        add(t, ab, cl, list(fi), list(ft), list(ipc), 0, 2008 + (i % 16))
    # 分野外 36 件
    for i in range(36):
        t, ab, cl, fi, ft, ipc = OTHER[i % len(OTHER)]
        add(t, ab, cl, list(fi), list(ft), list(ipc), 0, 2009 + (i % 15))
    # 引用関係（適合文献同士）
    rel_ids = [d["doc_id"] for d in docs if d["_rel"] == 3]
    for d in docs:
        if d["_rel"] == 3 and rng.random() < 0.6:
            d["citations"] = rng.sample([x for x in rel_ids if x != d["doc_id"]], 2)
    rng.shuffle(docs)
    return docs


def main() -> None:
    HERE.mkdir(parents=True, exist_ok=True)
    docs = make_docs()
    with (HERE / "population.csv").open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["文献番号", "発明の名称", "要約", "請求の範囲", "FI", "Fターム", "IPC", "公知日", "出願人/権利者", "引用文献"])
        for d in docs:
            w.writerow([d["doc_id"], d["title"], d["abstract"], d["claims"], ";".join(d["FI"]), ";".join(d["FT"]),
                        ";".join(d["IPC"]), d["pub_date"], d["applicant"], ";".join(d["citations"])])
    # 正解ラベル（後方テスト用。本番では存在しない）
    (HERE / "ground_truth.json").write_text(
        json.dumps({d["doc_id"]: d["_rel"] for d in docs}, ensure_ascii=False, indent=1), encoding="utf-8")
    # 既知文献 2 件
    seeds = [d for d in docs if d["_rel"] == 3][:2]
    (HERE / "seeds.json").write_text(json.dumps([
        {"doc_id": d["doc_id"], "title": d["title"], "abstract": d["abstract"], "claims": d["claims"],
         "codes": {"FI": d["FI"], "FT": d["FT"], "IPC": d["IPC"]}} for d in seeds], ensure_ascii=False, indent=1),
        encoding="utf-8")
    print(f"{len(docs)} docs, seeds={[s['doc_id'] for s in seeds]}")


if __name__ == "__main__":
    main()
